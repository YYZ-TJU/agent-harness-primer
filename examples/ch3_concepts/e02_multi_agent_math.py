"""例 2：拆成多个 agent，成功率会怎么变。

跑法：
    python examples/ch3_concepts/e02_multi_agent_math.py

这一章没有代码逻辑，只有一道乘法题。

但它是"要不要拆多 agent"最硬的一个判断依据。
"""
from __future__ import annotations


def chain_success(p, n):
    """串联 n 个步骤，每步成功率 p，整体成功率是多少。

    假设各步独立——这是个简化，真实系统里错误会相关（上游错导致下游也错），
    实际成功率往往比这个还低。
    """
    return p ** n


def main() -> None:
    print("=" * 64)
    print("① 单 agent 90%，拆成 3 个会怎样")
    print("=" * 64)
    print()

    p = 0.90
    print(f"  单 agent：        {p:.0%}")
    print(f"  拆成 2 个：       {chain_success(p, 2):.1%}   （{p:.0%} × {p:.0%}）")
    print(f"  拆成 3 个：       {chain_success(p, 3):.1%}   （{p:.0%}³）")
    print(f"  拆成 4 个：       {chain_success(p, 4):.1%}")
    print()
    print("  ↑ 从 90% 掉到 73%。多两个 agent，少 17 个百分点。")

    print()
    print("=" * 64)
    print("② 那什么情况下拆才划算")
    print("=" * 64)
    print()
    print("  关键：拆分能不能让每一步的准确率显著提高？")
    print()

    print(f"  {'每步准确率':>10s} {'3 步串联':>10s}   vs 单步 90%")
    print("  " + "-" * 44)
    for p in (0.90, 0.93, 0.95, 0.97, 0.98, 0.99):
        three = chain_success(p, 3)
        mark = "✓ 更好了" if three > 0.90 else ""
        print(f"  {p:>10.0%} {three:>10.1%}   {mark}")

    print()
    print("  ↑ 每步要到 96.5% 左右，3 步串联才追平单 agent 的 90%。")
    print("    要到 98%，才能明显超过。")

    print()
    print("=" * 64)
    print("③ 那为什么还有人多 agent")
    print("=" * 64)
    print("""
  因为有些任务，单 agent 根本做不到 90%。

  举个例子：合同审核 + 技术方案 + 财务测算

  单 agent 塞三个领域的规则到 prompt 里：
    · 规则互相干扰
    · 上下文太长
    · 实际准确率可能只有 60%

  拆成三个专才：
    · 每个 95%
    · 串联 = 0.95³ = 85.7%

  85.7% > 60%，这才值得拆。

  ─────────────────────────────────────────

  所以判断不是"多 agent 好不好"，
  而是「拆开后每步能提高多少」。

  公式：
    拆分收益 = 每步准确率提升  ×  步骤数
    拆分成本 = 0.9^n 的衰减

  先算账，再决定。
""")

    print("=" * 64)
    print("④ 一个反面例子")
    print("=" * 64)
    print("""
  猜猜这个配置的总体成功率：

    Agent A（抽取信息）     92%
    Agent B（校验格式）     99%
    Agent C（写数据库）     99%
    Agent D（发通知）       99%

  看起来只有 A 是瓶颈，其他都很稳。

  但串联：
    0.92 × 0.99 × 0.99 × 0.99 = 89.3%

  比单 agent 90% 还低。

  ─────────────────────────────────────────

  为什么？因为 B/C/D 那 1% 的失败也算在总数上。
  四个 99%，串起来只剩 96%。

  【这里能看出一个设计原则】

  如果 B/C/D 只是"格式校验"和"写库"，它们不该是 agent——
  应该是**代码**。

  代码的"成功率"接近 100%（写完就不会随机失败）。

  所以正确的拆分是：
    Agent A（抽取）→ 代码校验 → 代码写库 → 代码发通知

  这样只有一个 agent，成功率就是 92%。
""")

    print("=" * 64)
    print("结论")
    print("=" * 64)
    print("""
  1. 每多一个 agent，成功率乘一次
  2. 拆分只有在"每步准确率显著提高"时才划算
  3. 能用代码做的步骤，不要做成 agent
  4. 先算账，再决定拆不拆
""")


if __name__ == "__main__":
    main()
